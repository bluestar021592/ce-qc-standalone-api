import assert from 'node:assert/strict';
import fs from 'node:fs';
import {DatabaseSync} from 'node:sqlite';
import {qcDetailRead} from '../src/qcActionDetailRead.js';

const html=fs.readFileSync(new URL('../public/qc-action-detail.html',import.meta.url),'utf8');
const shell=fs.readFileSync(new URL('../public/v625-shell.js',import.meta.url),'utf8');
const server=fs.readFileSync(new URL('../server.js',import.meta.url),'utf8');
assert.match(html,/\.qcd-logo\{[^}]*max-width:94px/,'logo must remain small and bounded in the new CE QC brand header');
assert.match(html,/\.qcd-block\{[^}]*grid-template-columns:repeat\(2/,'desktop layout must remain two-column');
assert.match(html,/@media\(max-width:760px\)/,'detail must respond to narrow windows');
assert.match(html,/api\/qc-action-detail/,'detail must request the correct read-only API');
assert.doesNotMatch(html,/href="\/style\.css/,'must not rely on obsolete stylesheet');
assert.match(shell,/return '\/qc-action-detail\?'\+p\.toString\(\)/,'QC action must open dedicated page');
assert.match(shell,/if\(qcActionScope\?\.snapshotId\)p\.set\('snapshotId'/,'QC action must carry immutable snapshot');
assert.match(server,/app\.get\('\/api\/qc-action-detail'/,'the actual Express API must be mounted');

const db=new DatabaseSync(':memory:');
db.exec(`
CREATE TABLE unified_import_batches(snapshotId TEXT,batchId TEXT,reportDate TEXT,status TEXT,createdAt TEXT);
CREATE TABLE unified_import_rows(batchId TEXT,shipmentCode TEXT,businessType TEXT,reportDate TEXT,snapshotId TEXT,regionCode TEXT,recipientNormalized TEXT,sheetName TEXT,rowNumber INTEGER,classificationReason TEXT,rowJson TEXT);
CREATE TABLE business_scan_results(businessType TEXT,reportDate TEXT,shipmentCode TEXT,isPod INTEGER,orderStatus TEXT,updatedAt TEXT,rawJson TEXT);
CREATE TABLE business_final_rows(businessType TEXT,reportDate TEXT,shipmentCode TEXT,isPod INTEGER,primaryCategory TEXT,apiStatus TEXT,carryStatus TEXT,latestEventTime TEXT,latestEventDesc TEXT,latestNode TEXT,updatedAt TEXT,rawJson TEXT);
CREATE TABLE business_shipment_tracks(businessType TEXT,reportDate TEXT,shipmentCode TEXT,shipmentStatus TEXT,statusText TEXT,apiStatus TEXT,updatedAt TEXT,rawJson TEXT);
CREATE TABLE business_track_events(id INTEGER PRIMARY KEY,businessType TEXT,reportDate TEXT,shipmentCode TEXT,eventTime TEXT,eventCode TEXT,rawJson TEXT);
CREATE TABLE business_daily_parse_rows(id INTEGER PRIMARY KEY,businessType TEXT,reportDate TEXT,shipmentCode TEXT,sheetName TEXT,rowNumber INTEGER,source_row_number INTEGER,recipient_normalized TEXT,createdAt TEXT);
CREATE TABLE shipment_current_state(shipmentCode TEXT,businessType TEXT,reportDate TEXT,snapshotId TEXT,state TEXT,apiStatus TEXT,lastEventTime TEXT,updatedAt TEXT);
`);
const date='2026-07-04',bill='CE04072600013',snapshot='SNAP-V769-WHPP',other='SAME-BILL-CE';
db.prepare("INSERT INTO unified_import_batches VALUES(?,?,?,?,?)").run(snapshot,'B769',date,'VALID','2026-07-04T22:00:00');
db.prepare("INSERT INTO unified_import_rows VALUES(?,?,?,?,?,?,?,?,?,?,?)").run('B769',bill,'WHPP',date,snapshot,'PP','金边','sheet1',14,'WHPP store route','{}');
db.prepare("INSERT INTO unified_import_rows VALUES(?,?,?,?,?,?,?,?,?,?,?)").run('B769',other,'CE',date,snapshot,'PV','外省','sheet1',15,'CE delivery','{}');
db.prepare("INSERT INTO business_final_rows(businessType,reportDate,shipmentCode,isPod,primaryCategory,apiStatus,latestNode,rawJson) VALUES(?,?,?,?,?,?,?,?)")
  .run('CE',date,bill,1,'POD','60','成功签收','{}');
const original=db.prepare('SELECT COUNT(*) c FROM business_final_rows').get().c;
const a=qcDetailRead(db,{reportDate:date,shipmentCode:bill,businessType:'WHPP',snapshotId:snapshot});
assert.equal(a.ok,true);
assert.equal(a.detail.source.businessType,'WHPP');
assert.equal(a.detail.source.snapshotId,snapshot);
assert.equal(a.detail.source.regionCode,'PP');
assert.equal(a.detail.hasProcessingEvidence,false,'CCSL evidence must not leak into WHPP detail');
assert.equal(a.detail.finalRow,null);
assert.match(a.detail.notice,/已确认日报来源/,'verified import but no saved track remains explicit and never implies POD');
assert.equal(a.detail.evidence.source,true);
assert.equal(a.detail.evidence.trackEvents,0);
assert.equal(qcDetailRead(db,{reportDate:date,businessType:'CE',shipmentCode:bill,snapshotId:snapshot}).code,'QC_DETAIL_MEMBER_MISSING');
assert.equal(qcDetailRead(db,{reportDate:date,businessType:'WHPP',shipmentCode:bill,snapshotId:'OTHER-SNAP'}).code,'QC_DETAIL_SNAPSHOT_MISSING');
assert.equal(qcDetailRead(db,{reportDate:'2026-07-05',businessType:'WHPP',shipmentCode:bill,snapshotId:snapshot}).code,'QC_DETAIL_SNAPSHOT_MISSING');
db.prepare("INSERT INTO business_scan_results VALUES(?,?,?,?,?,?,?)").run('WHPP',date,bill,0,'70','2026-07-04T10:00:00','{}');
db.prepare("INSERT INTO business_shipment_tracks VALUES(?,?,?,?,?,?,?,?)").run('WHPP',date,bill,'80','退回中','SUCCESS','2026-07-04T11:00:00','{}');
db.prepare("INSERT INTO business_track_events VALUES(?,?,?,?,?,?,?)").run(1,'WHPP',date,bill,'2026-07-04T11:00:00','80','{"statusText":"退回中"}');
const b=qcDetailRead(db,{reportDate:date,shipmentCode:bill,businessType:'WHPP',snapshotId:snapshot});
assert.equal(b.detail.hasProcessingEvidence,true);
assert.equal(b.detail.scan.orderStatus,'70');
assert.equal(b.detail.track.shipmentStatus,'80');
assert.equal(b.detail.events.length,1);
assert.equal(b.detail.events[0].description,'退回中');
assert.equal(db.prepare('SELECT COUNT(*) c FROM business_final_rows').get().c,original,'detail must be read-only');
db.close();
console.log('[V769] actual WHPP daily source, scoped snapshot, missing saved track truth, live tracks, no cross-business leakage, responsive detail UI PASS');
