import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const js=fs.readFileSync('public/v625-shell.js','utf8');
const html=fs.readFileSync('public/v625-shell.html','utf8');
const from=js.indexOf('function v788TrackingReadOnlyReview(');
const until=js.indexOf('async function queryTrack(){',from);
assert.ok(from>0&&until>from,'exact production evidence helper');
const review=vm.runInNewContext(js.slice(from,until)+'\n v788TrackingReadOnlyReview;',{});
const bill='CC09052603760',other='CE00000000000';
const ledger={shipmentCode:bill,currentState:'CYCLE_COUNT',trackingStatus:'OPEN',lastEventTime:'2026-10-05 19:24:13'};
const events=[{eventTime:'2026-10-15 19:28:13'}];

const unknown=review({ledger:[ledger]},bill,events);
assert.match(unknown.result,/尚未发现可核实的POD或已退回终态/,'cycle count is not POD');
assert.equal(unknown.localState,'CYCLE_COUNT');
assert.equal(unknown.lastTime,'2026-10-15 19:28:13','event timeline time is independent of stale ledger timestamp');
assert.equal(unknown.hasTerminal,false);
assert.equal(unknown.openLedger,true);
assert.match(review({ledger:[ledger],remoteSkipped:'CE_AUTH_REQUIRED'},bill,events).remoteNote,/实时查询未得到完整响应/);
const pod=review({ledger:[ledger],shipmentRows:[{shipmentCode:bill,shipmentStatus:'60'}]},bill,events);
assert.match(pod.result,/POD终态证据.*账本仍OPEN/,'60 proves a conflict, never silently closes ledger');
assert.equal(pod.hasTerminal,true);
const done=review({ledger:[ledger],shipmentRows:[{shipmentCode:bill,shipmentStatus:'81'}]},bill,events);
assert.match(done.result,/已退回终态证据.*账本仍OPEN/);
assert.match(review({ledger:[ledger],shipmentRows:[{shipmentCode:bill,shipmentStatus:'80'}]},bill,events).result,/退回处理中/);
assert.equal(review({ledger:[ledger],scanRows:[{shipmentCode:bill,orderStatus:'85'}]},bill,events).hasTerminal,true);
assert.equal(review({ledger:[ledger],shipmentRows:[{shipmentCode:other,shipmentStatus:'60'}]},bill,events).hasTerminal,false,'never trust another bill status');
assert.equal(review({ledger:[ledger],shipmentRows:[{shipmentCode:bill,shipmentStatus:'60'},{shipmentCode:bill,shipmentStatus:'81'}]},bill,events).conflict,true);
assert.match(js,/轨迹记录（最新在前）/);
assert.match(js,/return key\(b\)\.localeCompare\(key\(a\)\)/,'latest visible evidence first');
assert.match(js,/CYCLE_COUNT（盘点）不等于POD或已退回/);
assert.match(html,/v625-shell\.js\?v=20261019-v788-1&patch=792/);
console.log('[V788 TRACKING LATEST] PASS last event first; CYCLE_COUNT open; 60/80/81 exact bill states; conflicts and remote errors retained; no ledger writes');
